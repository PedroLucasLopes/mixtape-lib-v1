import { writeFileSync } from 'node:fs';
import * as icons from 'simple-icons';

const WANTED = {
  spotify: 'siSpotify',
  appleMusic: 'siApplemusic',
  deezer: 'siDeezer',
  youtubeMusic: 'siYoutubemusic',
  youtube: 'siYoutube',
  tidal: 'siTidal',
  soundcloud: 'siSoundcloud',
  bandcamp: 'siBandcamp',
  whatsapp: 'siWhatsapp',
  telegram: 'siTelegram',
  x: 'siX',
  facebook: 'siFacebook',
  instagram: 'siInstagram',
  threads: 'siThreads',
  bluesky: 'siBluesky',
  tiktok: 'siTiktok',
  wikipedia: 'siWikipedia',
  wikidata: 'siWikidata',
  lastfm: 'siLastdotfm',
  discogs: 'siDiscogs',
  musicbrainz: 'siMusicbrainz',
};

const entries = Object.entries(WANTED).map(([name, exportName]) => {
  const icon = icons[exportName];
  if (!icon) throw new Error(`simple-icons has no ${exportName}`);
  return `  ${name}: { title: ${JSON.stringify(icon.title)}, hex: ${JSON.stringify(icon.hex)}, path: ${JSON.stringify(icon.path)} },`;
});

const version = JSON.parse(
  await import('node:fs').then(({ readFileSync }) => readFileSync(new URL('../node_modules/simple-icons/package.json', import.meta.url), 'utf8')),
).version;

const source = [
  `// Generated by scripts/sync-brand-icons.mjs from simple-icons ${version} (CC0-1.0). Do not edit.`,
  'export const BRAND_ICONS = {',
  ...entries,
  '} as const;',
  '',
].join('\n');

writeFileSync(new URL('../src/components/brand-icons.generated.ts', import.meta.url), source, 'utf8');
console.log(`brand icons written: ${entries.length} (simple-icons ${version})`);
